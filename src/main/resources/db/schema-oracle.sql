-- TRANSACTIONS : 입금 기록 (FR-017, FR-018, FR-012d)
--   REVERSAL(취소) / RE_PAYMENT(재지급)은 ORIGINAL_TRANSACTION_ID 로 원거래를 가리킨다.
--   사용자가 직접 호출하는 API 는 없고 재판정 로직 내부에서만 생성된다.
--------------------------------------------------------------------------------
CREATE TABLE TRANSACTIONS (
    ID                      NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
    ACCOUNT_ID              NUMBER(19)   NOT NULL,
    MISSION_LOG_ID          NUMBER(19)   NOT NULL,
    ORIGINAL_TRANSACTION_ID NUMBER(19),                          -- REVERSAL / RE_PAYMENT 일 때만 값 존재
    AMOUNT                  NUMBER(15)   NOT NULL,               -- REVERSAL 은 음수
    TX_TYPE                 VARCHAR2(20) NOT NULL,               -- MISSION_REWARD / REVERSAL / RE_PAYMENT
    CREATED_AT              TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (ID),
    CONSTRAINT FK_TRANSACTIONS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNT (ID),
    CONSTRAINT FK_TRANSACTIONS_MISSION_LOG FOREIGN KEY (MISSION_LOG_ID) REFERENCES MISSION_LOG (ID),
    CONSTRAINT FK_TRANSACTIONS_ORIGINAL FOREIGN KEY (ORIGINAL_TRANSACTION_ID) REFERENCES TRANSACTIONS (ID),
    CONSTRAINT CK_TRANSACTIONS_TX_TYPE CHECK (
        TX_TYPE IN ('MISSION_REWARD', 'REVERSAL', 'RE_PAYMENT'))
);

CREATE INDEX IX_TRANSACTIONS_ACCOUNT ON TRANSACTIONS (ACCOUNT_ID, CREATED_AT DESC);
CREATE INDEX IX_TRANSACTIONS_MISSION_LOG ON TRANSACTIONS (MISSION_LOG_ID);

