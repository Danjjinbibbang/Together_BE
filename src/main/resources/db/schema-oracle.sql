-- MISSION : 미션 마스터 (FR-007 ~ FR-010)
--   방장이 직접 만들거나(CREATED_BY_TYPE='OWNER') AI 제안을 골라 등록한다('AI').
--   AI 생성 API 는 제안만 돌려주고 저장하지 않으므로, 저장 시점에는 항상 방장이 개입한다.
--
--   [확인필요] CHALLENGE_ID 를 nullable 로 남겨 전역 고정 풀 시드를 유지했다. API 명세서의
--     미션 엔드포인트는 전부 챌린지 하위라, 전역 풀을 폐지하고 NOT NULL 로 바꿔야 할 수도 있다.
--------------------------------------------------------------------------------
CREATE TABLE MISSION (
    ID                   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    CHALLENGE_ID         NUMBER(19),                             -- NULL = 전역 공용 고정 풀
    TITLE                VARCHAR2(200) NOT NULL,
    SUBMIT_TYPE          VARCHAR2(10)  DEFAULT 'TEXT' NOT NULL,  -- TEXT / PHOTO
    -- 보상은 고정값이 아니라 범위다(FR-013 100~10,000원 균등 랜덤).
    -- 실제 금액은 배정 시점에 이 범위 안에서 한 번 뽑아 DAILY_MISSION_ASSIGNMENT 에 저장한다.
    REWARD_MIN           NUMBER(7),
    REWARD_MAX           NUMBER(7),
    MIN_TEXT_LENGTH      NUMBER(5),                              -- TEXT 미션 자동완료 기준. PHOTO 면 NULL
    CREATED_BY_TYPE      VARCHAR2(10),                           -- OWNER / AI. 전역 고정 풀은 NULL
    CREATED_BY_MEMBER_ID NUMBER(19),                             -- AI 생성도 등록한 방장을 남긴다
    IS_ACTIVE            CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_MISSION PRIMARY KEY (ID),
    CONSTRAINT FK_MISSION_CHALLENGE FOREIGN KEY (CHALLENGE_ID) REFERENCES CHALLENGE (ID),
    CONSTRAINT FK_MISSION_CREATED_BY FOREIGN KEY (CREATED_BY_MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT CK_MISSION_SUBMIT_TYPE CHECK (SUBMIT_TYPE IN ('TEXT', 'PHOTO')),
    CONSTRAINT CK_MISSION_CREATED_BY_TYPE CHECK (CREATED_BY_TYPE IN ('OWNER', 'AI')),
    CONSTRAINT CK_MISSION_REWARD_RANGE CHECK (
        REWARD_MIN >= 100 AND REWARD_MAX <= 10000 AND REWARD_MIN <= REWARD_MAX),
    CONSTRAINT CK_MISSION_IS_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

CREATE INDEX IX_MISSION_CHALLENGE ON MISSION (CHALLENGE_ID, IS_ACTIVE);

--------------------------------------------------------------------------------
-- DAILY_MISSION_ASSIGNMENT : 오늘의 미션 배정 (FR-010)
--   챌린지당 하루 1건. GET /challenges/{id}/missions/today 최초 호출 시 서버가 랜덤 배정을
--   생성하고, 이후 호출은 같은 행을 돌려준다.
--
--   REWARD_AMOUNT 는 배정 시점에 MISSION.REWARD_MIN~REWARD_MAX 에서 균등 랜덤으로 한 번만
--   뽑아 고정한다. 같은 날·같은 챌린지의 멤버는 모두 같은 금액을 받는다 — 함께 수행하는
--   미션인데 보상이 다르면 팀 안에서 불공정하게 느껴지기 때문이다.
--   이 값은 today 응답에 담지 않는다(범위만 노출). 미션 완료 후 화면 12에서 처음 공개된다.
--------------------------------------------------------------------------------
CREATE TABLE DAILY_MISSION_ASSIGNMENT (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CHALLENGE_ID  NUMBER(19) NOT NULL,
    MISSION_ID    NUMBER(19) NOT NULL,
    ASSIGNED_DATE DATE       NOT NULL,
    REWARD_AMOUNT NUMBER(7)  NOT NULL,                           -- 배정 시점에 확정된 금액
    CREATED_AT    TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DAILY_MISSION_ASSIGNMENT PRIMARY KEY (ID),
    CONSTRAINT FK_DMA_CHALLENGE FOREIGN KEY (CHALLENGE_ID) REFERENCES CHALLENGE (ID),
    CONSTRAINT FK_DMA_MISSION FOREIGN KEY (MISSION_ID) REFERENCES MISSION (ID),
    CONSTRAINT UK_DMA_CHALLENGE_DATE UNIQUE (CHALLENGE_ID, ASSIGNED_DATE),
    CONSTRAINT CK_DMA_REWARD CHECK (REWARD_AMOUNT BETWEEN 100 AND 10000)
);

--------------------------------------------------------------------------------
-- MISSION_LOG : 미션 수행 기록 (FR-011 ~ FR-016)
--   하루 1미션 제한은 UK_MISSION_LOG_MEMBER_ASSIGNMENT 가 보장한다(배정 자체가 하루 1건).
--   중복 제출 시 이 제약 위반 → 409.
--
--   상태 흐름 (FR-012, 8단계)
--     SUBMITTED ──AI판정──> AI_APPROVED
--                       └─> AI_REJECTED ──이의제기──> DISPUTE_REQUESTED
--                                                  ├─> RECHECK_REQUESTED (그대로 재검토)
--                                                  └─> RESUBMITTED       (수정 후 재제출)
--                                                        └─방장판정─> OWNER_APPROVED / OWNER_REJECTED
--------------------------------------------------------------------------------
CREATE TABLE MISSION_LOG (
    ID                 NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
    MEMBER_ID          NUMBER(19)   NOT NULL,
    ASSIGNMENT_ID      NUMBER(19)   NOT NULL,
    SUBMIT_CONTENT     CLOB,                                     -- 텍스트 미션 작성 내용
    ATTACHMENT_URL     VARCHAR2(500),                            -- 사진 미션 증빙 경로
    -- 완료 처리 시 DAILY_MISSION_ASSIGNMENT.REWARD_AMOUNT 를 복사해 넣는다
    REWARD_AMOUNT      NUMBER(7),
    IS_PUBLIC          CHAR(1)      DEFAULT 'Y' NOT NULL,        -- FR-015 기본값 공개
    STATUS             VARCHAR2(20) NOT NULL,
    REVIEWED_BY        VARCHAR2(10),                             -- 마지막 판정 주체. AI / OWNER
    REJECT_REASON_CODE VARCHAR2(20),                             -- 반려 사유. 없으면 NULL
    RESUBMIT_COUNT     NUMBER(3)    DEFAULT 0 NOT NULL,          -- FR-012b
    -- 방장 판정을 기다리기 시작한 시각(FR-012c). 무응답 자동 승인 기한을 여기서 잰다.
    REVIEW_REQUESTED_AT TIMESTAMP,
    COMPLETED_AT       TIMESTAMP,
    CREATED_AT         TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MISSION_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_MISSION_LOG_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT FK_MISSION_LOG_ASSIGNMENT FOREIGN KEY (ASSIGNMENT_ID)
        REFERENCES DAILY_MISSION_ASSIGNMENT (ID),
    CONSTRAINT UK_MISSION_LOG_MEMBER_ASSIGNMENT UNIQUE (MEMBER_ID, ASSIGNMENT_ID),
    CONSTRAINT CK_MISSION_LOG_IS_PUBLIC CHECK (IS_PUBLIC IN ('Y', 'N')),
    CONSTRAINT CK_MISSION_LOG_STATUS CHECK (
        STATUS IN ('SUBMITTED',
                   'AI_APPROVED', 'AI_REJECTED',
                   'DISPUTE_REQUESTED',
                   'RECHECK_REQUESTED', 'RESUBMITTED',
                   'OWNER_APPROVED', 'OWNER_REJECTED')),
    -- AUTO = 방장이 기한 내에 판정하지 않아 자동 승인된 건(FR-012c)
    CONSTRAINT CK_MISSION_LOG_REVIEWED_BY CHECK (REVIEWED_BY IN ('AI', 'OWNER', 'AUTO')),
    -- 화질불량 / 조도부족 / 주제무관 / 기타
    CONSTRAINT CK_MISSION_LOG_REASON CHECK (
        REJECT_REASON_CODE IN ('LOW_QUALITY', 'LOW_LIGHT', 'IRRELEVANT', 'ETC')),
    CONSTRAINT CK_MISSION_LOG_REWARD CHECK (REWARD_AMOUNT BETWEEN 100 AND 10000)
);

CREATE INDEX IX_MISSION_LOG_MEMBER ON MISSION_LOG (MEMBER_ID, CREATED_AT DESC);
CREATE INDEX IX_MISSION_LOG_ASSIGNMENT ON MISSION_LOG (ASSIGNMENT_ID);
CREATE INDEX IX_MISSION_LOG_STATUS ON MISSION_LOG (STATUS);

