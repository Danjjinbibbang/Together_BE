-- MEMBER : 챌린지별 참여 정보 (FR-003, FR-004, FR-006)
--   방장 정보의 유일한 소스는 이 테이블의 ROLE 이다. 방장 양도는 CHALLENGE 를 건드리지 않고
--   ROLE UPDATE 2건으로 처리한다.
--
--   [확인필요] STATUS 에서 INVITED 가 빠졌다. API 명세서에는 ACTIVE / LEFT 만 등장하는데,
--     요구사항 FR-004/FR-006 의 "초대됨(읽기 전용)" 상태가 폐지된 것인지 명세에서 누락된
--     것인지 불명확하다. 명세를 따라 두 값만 허용한다.
--------------------------------------------------------------------------------
CREATE TABLE MEMBER (
    ID           NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
    USER_ID      NUMBER(19)   NOT NULL,
    CHALLENGE_ID NUMBER(19)   NOT NULL,
    NICKNAME     VARCHAR2(30) NOT NULL,
    ROLE         VARCHAR2(10) DEFAULT 'MEMBER' NOT NULL,         -- OWNER(방장) / MEMBER(팀원)
    STATUS       VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,         -- ACTIVE / LEFT(탈퇴, FR-038)
    THEME_COLOR  VARCHAR2(20),                                   -- FR-041 캘린더 색상(개인 설정, 예 '#18A8F1')
    -- 알림 수신 설정은 종류별로 켜고 끌 수 있어야 해서 MEMBER_NOTIFICATION_SETTING 으로 분리했다.
    JOINED_AT    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MEMBER PRIMARY KEY (ID),
    CONSTRAINT FK_MEMBER_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_MEMBER_CHALLENGE FOREIGN KEY (CHALLENGE_ID) REFERENCES CHALLENGE (ID),
    CONSTRAINT UK_MEMBER_USER_CHALLENGE UNIQUE (USER_ID, CHALLENGE_ID),
    CONSTRAINT UK_MEMBER_CHALLENGE_NICKNAME UNIQUE (CHALLENGE_ID, NICKNAME),
    CONSTRAINT CK_MEMBER_ROLE CHECK (ROLE IN ('OWNER', 'MEMBER')),
    CONSTRAINT CK_MEMBER_STATUS CHECK (STATUS IN ('ACTIVE', 'LEFT'))
);

CREATE INDEX IX_MEMBER_USER ON MEMBER (USER_ID);

--------------------------------------------------------------------------------
-- MEMBER_NOTIFICATION_SETTING : 챌린지별·종류별 알림 수신 설정 (개인 설정)
--   컬럼을 종류마다 늘리는 대신 행으로 뒀다. 알림 종류가 아직 확정 전이라 늘거나 줄 수 있는데,
--   그때마다 DDL 을 고치지 않아도 되게 하려는 것이다.
--
--   행이 없으면 '켜짐'으로 본다. 끈 것만 저장하므로 새 종류가 생겨도 백필이 필요 없고,
--   기본이 수신인 정책과도 맞는다.
--
--   NOTI_TYPE 에 CHECK 를 걸지 않은 이유는 NOTIFICATION.NOTI_TYPE 과 같다 — 목록 미확정.
--------------------------------------------------------------------------------
CREATE TABLE MEMBER_NOTIFICATION_SETTING (
    MEMBER_ID NUMBER(19)   NOT NULL,
    NOTI_TYPE VARCHAR2(30) NOT NULL,
    ENABLED   CHAR(1)      DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_MEMBER_NOTI_SETTING PRIMARY KEY (MEMBER_ID, NOTI_TYPE),
    CONSTRAINT FK_MNS_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT CK_MNS_ENABLED CHECK (ENABLED IN ('Y', 'N'))
);

