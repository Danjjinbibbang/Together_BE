-- CHALLENGE : 챌린지 (FR-001, FR-007, FR-036)
--   MISSION_MODE 는 생성 시점에 정하지 않는다. POST /challenges 응답이 null 을 내려주고,
--   방장이 PATCH /challenges/{id}/mission-mode 로 나중에 설정한다.
--------------------------------------------------------------------------------
CREATE TABLE CHALLENGE (
    ID            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    TITLE         VARCHAR2(100) NOT NULL,
    TARGET_AMOUNT NUMBER(15)    NOT NULL,                        -- API 필드명은 goalAmount
    START_DATE    DATE          NOT NULL,
    END_DATE      DATE          NOT NULL,
    INVITE_CODE   VARCHAR2(20)  NOT NULL,
    MISSION_MODE  VARCHAR2(10),                                  -- FIXED / AI. 미설정이면 NULL
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CHALLENGE PRIMARY KEY (ID),
    CONSTRAINT UK_CHALLENGE_INVITE_CODE UNIQUE (INVITE_CODE),
    CONSTRAINT CK_CHALLENGE_MISSION_MODE CHECK (MISSION_MODE IN ('FIXED', 'AI')),
    CONSTRAINT CK_CHALLENGE_PERIOD CHECK (END_DATE >= START_DATE),
    CONSTRAINT CK_CHALLENGE_TARGET_AMOUNT CHECK (TARGET_AMOUNT > 0)
);

