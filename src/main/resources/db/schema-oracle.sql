-- USERS : 카카오 로그인으로 생성되는 전역 계정 (FR-030)
--------------------------------------------------------------------------------
CREATE TABLE USERS (
    ID              NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
    KAKAO_ID        VARCHAR2(64) NOT NULL,
    EMAIL           VARCHAR2(255),
    TERMS_AGREED_AT TIMESTAMP,                                   -- FR-028 약관 동의 일시
    TERMS_VERSION   VARCHAR2(20),                                -- FR-028 동의한 약관 버전
    CREATED_AT      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    -- FR-043 계정 탈퇴. NULL 이면 활성 계정. 행을 지우지 않는 이유는 MEMBER 를 참조하는
    -- 과거 기록(미션 로그·거래·댓글)이 남아야 하기 때문이다. 탈퇴 시 KAKAO_ID 는
    -- 'withdrawn:'||ID 로, EMAIL 은 NULL 로 치환한다(개인정보 파기 + 같은 카카오 계정 재가입 허용).
    WITHDRAWN_AT    TIMESTAMP,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_USERS_KAKAO_ID UNIQUE (KAKAO_ID)
);

