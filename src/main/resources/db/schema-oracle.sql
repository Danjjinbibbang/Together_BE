    BALANCE   NUMBER(15) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (ID),
    CONSTRAINT FK_ACCOUNT_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT UK_ACCOUNT_MEMBER UNIQUE (MEMBER_ID),
    CONSTRAINT CK_ACCOUNT_BALANCE CHECK (BALANCE >= 0)
);

