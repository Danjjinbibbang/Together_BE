--
-- 명명 규칙
--   * USER / COMMENT 는 Oracle 예약어라 USERS / COMMENTS 로 복수형을 쓴다.
--     TRANSACTION 도 충돌 소지가 있어 TRANSACTIONS 로 통일했다.
--     그 외에는 단수형이다. Notion 문서는 복수형(MEMBERS 등)으로 적혀 있으나 테이블명은
--     API 계약에 노출되지 않으므로 이 파일의 기존 규칙을 유지했다.
--   * enum 값은 API 명세서의 응답 예시를 정답으로 삼는다. DB 값과 JSON 값이 같아야
--     서비스 계층에서 변환할 일이 없다.
--   * boolean 은 CHAR(1) 'Y'/'N'. JSON 에서는 true/false 로 내려간다.
--   * 컬럼명은 API 필드명과 맞췄다(submitContent, attachmentUrl, rejectReasonCode 등).
--     map-underscore-to-camel-case 로 그대로 매핑되게 하기 위함이다.
--
-- API 명세서 반영으로 v0.4 최초안에서 바뀐 것
--   * MEMBER.ROLE      LEADER → OWNER
--   * MEMBER.STATUS    INVITED/JOINED/LEFT → ACTIVE/LEFT  ([확인필요] 아래 참고)
--   * TRANSACTIONS.TX_TYPE  PAYOUT/CLAWBACK/REPAYOUT → MISSION_REWARD/REVERSAL/RE_PAYMENT
--   * REACTION 제약     멤버당 이모지별 1개 → 멤버당 1개 (다른 타입 누르면 교체)
--   * CHALLENGE.MISSION_MODE  NOT NULL DEFAULT 'FIXED' → nullable (생성 직후 null, 이후 설정)
--   * MISSION 에서 DIFFICULTY / DESCRIPTION / SOURCE_TYPE 제거 (어떤 응답에도 없음)
--   * 보상 금액이 고정값 → 범위로 변경 (claude 컨텍스트 §12, 2026-08-20)
--     MISSION.REWARD_AMOUNT → REWARD_MIN/REWARD_MAX,
--     DAILY_MISSION_ASSIGNMENT.REWARD_AMOUNT 신설(배정 시점에 한 번만 추첨)
--   * 컬럼명 정렬: PROOF_TYPE→SUBMIT_TYPE, MIN_LENGTH→MIN_TEXT_LENGTH,
--                  CONTENT→SUBMIT_CONTENT, PHOTO_URL→ATTACHMENT_URL,
--                  MISDETECT_REASON_CODE→REJECT_REASON_CODE, EMOJI_TYPE→REACTION_TYPE,
--                  NOTIFICATION.MESSAGE→CONTENT
--
-- 2026-08-25 추가
--   * USERS.WITHDRAWN_AT 신설 — FR-043 계정 탈퇴(DELETE /users/me)
--   * 캘린더(FR-027/FR-040)·스트릭(FR-025)은 기존 테이블 집계라 스키마 변경이 없다
--   * 이미 만들어진 DB 는 migration-2026-08-25.sql 로 따라잡는다
--
-- 2026-08-25 (2) 추가 — 요구사항정의서 v0.4 §4 "계속 미정" 4건 구현분
--   * MISSION_MODE_VOTE / MISSION_MODE_VOTE_BALLOT 신설 — FR-008 미션 방식 팀원 투표
--   * MISSION_LOG.REVIEW_REQUESTED_AT 신설, REVIEWED_BY 에 AUTO 허용 — FR-012c 무응답 자동 승인
--   * REFRESH_TOKEN 신설 — FR-035 리프레시 토큰
--   * 이미 만들어진 DB 는 migration-2026-08-25-open-issues.sql 로 따라잡는다
