-- NOTIFICATION : 알림 (FR-020, FR-021, FR-012a)
--   TARGET_TYPE + TARGET_ID 다형 참조. DB 레벨 FK 를 걸 수 없으므로 대상 존재 보장은 서비스 몫.
--
--   [확인필요] NOTI_TYPE / TARGET_TYPE 에 CHECK 를 걸지 않았다. API 명세서가 예시로
--     MISSION_REWARD, MISSION_LOG/CHALLENGE "등"만 들고 전체 목록을 정의하지 않아,
--     지금 제약을 걸면 정의되지 않은 정상 값을 거부하게 된다. 목록 확정 후 CHECK 추가할 것.
--------------------------------------------------------------------------------
CREATE TABLE NOTIFICATION (
    ID                 NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    RECEIVER_MEMBER_ID NUMBER(19)    NOT NULL,
    NOTI_TYPE          VARCHAR2(30)  NOT NULL,                   -- 예: MISSION_REWARD (API 필드명은 type)
    CONTENT            VARCHAR2(500),                            -- 알림 문구
    TARGET_TYPE        VARCHAR2(30),                             -- 예: MISSION_LOG / CHALLENGE
    TARGET_ID          NUMBER(19),
    IS_READ            CHAR(1)       DEFAULT 'N' NOT NULL,
    CREATED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICATION PRIMARY KEY (ID),
    CONSTRAINT FK_NOTIFICATION_RECEIVER FOREIGN KEY (RECEIVER_MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT CK_NOTIFICATION_IS_READ CHECK (IS_READ IN ('Y', 'N')),
    -- 대상 타입과 ID 는 항상 함께 있거나 함께 없어야 한다
    CONSTRAINT CK_NOTIFICATION_TARGET_PAIR CHECK (
        (TARGET_TYPE IS NULL AND TARGET_ID IS NULL)
        OR (TARGET_TYPE IS NOT NULL AND TARGET_ID IS NOT NULL))
);

-- 폴링 기반 알림함 조회(FR-021) / 미확인 개수 조회용
CREATE INDEX IX_NOTIFICATION_RECEIVER ON NOTIFICATION (RECEIVER_MEMBER_ID, IS_READ, CREATED_AT DESC);

