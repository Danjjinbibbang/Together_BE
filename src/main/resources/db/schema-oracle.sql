--------------------------------------------------------------------------------
-- ① 미션 방식 팀원 투표 (FR-008)
--   방장이 단독으로 정하던 MISSION_MODE 를 팀원 투표로 정할 수 있게 한다.
--   확정 결과는 CHALLENGE.MISSION_MODE 에 그대로 반영되므로, 투표는 "결정 과정"만 남긴다.
--------------------------------------------------------------------------------
CREATE TABLE MISSION_MODE_VOTE (
    ID                   NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
    CHALLENGE_ID         NUMBER(19)   NOT NULL,
    STATUS               VARCHAR2(10) DEFAULT 'OPEN' NOT NULL,   -- OPEN / CLOSED
    DEADLINE             TIMESTAMP    NOT NULL,                  -- 지나면 조회·투표 시점에 자동 마감된다
    -- 마감 결과. DECIDED(다수결 확정) / TIE(동률) / NOT_ENOUGH_VOTES(정족수 미달)
    OUTCOME              VARCHAR2(20),
    RESULT_MODE          VARCHAR2(10),                           -- DECIDED 일 때만. FIXED / AI
    OPENED_BY_MEMBER_ID  NUMBER(19)   NOT NULL,
    CREATED_AT           TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CLOSED_AT            TIMESTAMP,
    CONSTRAINT PK_MISSION_MODE_VOTE PRIMARY KEY (ID),
    CONSTRAINT FK_MMV_CHALLENGE FOREIGN KEY (CHALLENGE_ID) REFERENCES CHALLENGE (ID),
    CONSTRAINT FK_MMV_OPENED_BY FOREIGN KEY (OPENED_BY_MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT CK_MMV_STATUS CHECK (STATUS IN ('OPEN', 'CLOSED')),
    CONSTRAINT CK_MMV_OUTCOME CHECK (OUTCOME IN ('DECIDED', 'TIE', 'NOT_ENOUGH_VOTES')),
    CONSTRAINT CK_MMV_RESULT_MODE CHECK (RESULT_MODE IN ('FIXED', 'AI')),
    -- 열려 있는 동안에는 결과가 없고, 닫히면 결과가 있어야 한다
    CONSTRAINT CK_MMV_CLOSED_HAS_OUTCOME CHECK (
        (STATUS = 'OPEN'   AND OUTCOME IS NULL AND CLOSED_AT IS NULL)
        OR (STATUS = 'CLOSED' AND OUTCOME IS NOT NULL AND CLOSED_AT IS NOT NULL))
);

-- 챌린지당 열린 투표는 하나뿐이다. 닫힌 것은 이력으로 얼마든지 쌓인다.
-- (부분 인덱스가 없는 Oracle 에서는 CASE 식으로 같은 효과를 낸다 — OPEN 이 아닌 행은 NULL 이라 제외된다.)
CREATE UNIQUE INDEX UX_MMV_OPEN_PER_CHALLENGE
    ON MISSION_MODE_VOTE (CASE WHEN STATUS = 'OPEN' THEN CHALLENGE_ID END);

CREATE INDEX IX_MMV_CHALLENGE ON MISSION_MODE_VOTE (CHALLENGE_ID, ID DESC);

--------------------------------------------------------------------------------
-- MISSION_MODE_VOTE_BALLOT : 한 사람이 한 투표에 한 표.
--   마음을 바꾸면 새 행이 아니라 CHOICE 를 갱신한다(PK 가 재투표를 막아준다).
--------------------------------------------------------------------------------
CREATE TABLE MISSION_MODE_VOTE_BALLOT (
    VOTE_ID   NUMBER(19)   NOT NULL,
    MEMBER_ID NUMBER(19)   NOT NULL,
    CHOICE    VARCHAR2(10) NOT NULL,                             -- FIXED / AI
    VOTED_AT  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MMV_BALLOT PRIMARY KEY (VOTE_ID, MEMBER_ID),
    CONSTRAINT FK_MMVB_VOTE FOREIGN KEY (VOTE_ID) REFERENCES MISSION_MODE_VOTE (ID),
    CONSTRAINT FK_MMVB_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (ID),
    CONSTRAINT CK_MMVB_CHOICE CHECK (CHOICE IN ('FIXED', 'AI'))
);


--------------------------------------------------------------------------------
-- ③ 리프레시 토큰 (FR-035)
--   원문은 저장하지 않고 SHA-256 해시만 둔다 — DB 가 새도 토큰을 재현할 수 없어야 한다.
--   회전(rotation) 방식이라 재발급 때마다 이전 토큰을 폐기하고 새 행을 만든다.
--------------------------------------------------------------------------------
CREATE TABLE REFRESH_TOKEN (
    ID         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    USER_ID    NUMBER(19)    NOT NULL,
    TOKEN_HASH VARCHAR2(64)  NOT NULL,                           -- SHA-256 hex
    EXPIRES_AT TIMESTAMP     NOT NULL,
    REVOKED_AT TIMESTAMP,                                        -- NULL 이면 살아 있는 토큰
    CREATED_AT TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REFRESH_TOKEN PRIMARY KEY (ID),
    CONSTRAINT FK_REFRESH_TOKEN_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT UK_REFRESH_TOKEN_HASH UNIQUE (TOKEN_HASH)
);

-- 로그아웃·계정탈퇴·재사용 감지에서 한 사용자의 토큰을 통째로 폐기할 때 쓴다.
CREATE INDEX IX_REFRESH_TOKEN_USER ON REFRESH_TOKEN (USER_ID, REVOKED_AT);

--------------------------------------------------------------------------------
-- TEAM_MESSAGE : 팀 응원 메시지 (FR-044) — 팀원 누구나 팀 전체에 한 줄 보낸다.
--   실시간 채팅(MVP 제외)이 아니라 단건 발송이고, 받는 쪽은 알림함에서 읽는다.
--   NOTIFICATION 만으로 안 되는 이유는 발신자·도배 카운트·원본 하나 유지 셋이다.
--------------------------------------------------------------------------------
CREATE TABLE TEAM_MESSAGE (
    ID               NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    CHALLENGE_ID     NUMBER(19)       NOT NULL,
    SENDER_MEMBER_ID NUMBER(19)       NOT NULL,
    -- 다른 테이블은 바이트 기준이지만 여기만 글자 기준이다. 한글 200자를 그대로 받아야 하는데
    -- VARCHAR2(200) 이면 바이트 기준이라 67자에서 잘린다.
    CONTENT          VARCHAR2(200 CHAR) NOT NULL,
    CREATED_AT       TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
    -- 수정·삭제 시각. 삭제는 soft delete 다 — 알림함에서는 흔적 없이 사라지지만(알림 행은 실제로
    -- 지운다) 원본은 남겨, 지우고 다시 보내는 식으로 하루 발송 한도를 우회하지 못하게 한다.
    UPDATED_AT       TIMESTAMP,
    DELETED_AT       TIMESTAMP,
    CONSTRAINT PK_TEAM_MESSAGE PRIMARY KEY (ID),
    CONSTRAINT FK_TEAM_MESSAGE_CHALLENGE FOREIGN KEY (CHALLENGE_ID) REFERENCES CHALLENGE (ID),
    CONSTRAINT FK_TEAM_MESSAGE_SENDER FOREIGN KEY (SENDER_MEMBER_ID) REFERENCES MEMBER (ID)
);

-- 목록 조회(커서 페이지네이션)는 최신순이다.
CREATE INDEX IX_TEAM_MESSAGE_CHALLENGE ON TEAM_MESSAGE (CHALLENGE_ID, ID DESC);

-- 하루 발송 횟수 제한을 셀 때 쓴다.
CREATE INDEX IX_TEAM_MESSAGE_SENDER ON TEAM_MESSAGE (SENDER_MEMBER_ID, CREATED_AT);

-- 원본 하나로 알림 여러 건을 되짚어 갈 때 쓴다(메시지 수정·삭제가 알림을 따라가야 해서).
CREATE INDEX IX_NOTIFICATION_TARGET ON NOTIFICATION (TARGET_TYPE, TARGET_ID);
