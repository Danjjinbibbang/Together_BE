-- 알림(NOTIFICATION.CONTENT)은 발송 시점의 스냅샷이라, 원본만 고치면 팀원 알림함에는
-- 옛 문구가 그대로 남는다. 그래서 수정·삭제 때 알림 행까지 같은 트랜잭션에서 손본다.
--
-- 조회(알림함 목록 + 미확인 개수)는 폴링으로 계속 불리는 경로라 건드리지 않았다.
-- 대신 어쩌다 한 번인 수정·삭제 쪽이 팀원 수만큼 행을 갱신한다.
--------------------------------------------------------------------------------

-- 수정 시각과 삭제 시각. 둘 다 NULL 이면 한 번도 고치지 않은 살아 있는 메시지다.
--
-- 삭제는 soft delete 다. 알림함에서는 흔적 없이 사라지지만(알림 행은 실제로 지운다)
-- 원본은 남겨 둔다 — 지우고 다시 보내는 식으로 하루 발송 한도를 우회하는 것을 막고,
-- 누가 언제 무엇을 지웠는지도 남는다.
ALTER TABLE TEAM_MESSAGE ADD (UPDATED_AT TIMESTAMP, DELETED_AT TIMESTAMP);

-- 알림을 대상(TARGET_TYPE + TARGET_ID)으로 되짚어 갈 때 쓴다. 지금까지는 수신자 기준으로만
-- 읽어서 필요 없었지만, 원본 하나로 알림 여러 건을 찾아야 하는 경로가 처음 생겼다.
CREATE INDEX IX_NOTIFICATION_TARGET ON NOTIFICATION (TARGET_TYPE, TARGET_ID);
